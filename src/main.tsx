// ============================================================
// main.tsx ― アプリケーションのエントリーポイント
//
// 【エントリーポイントとは？】
// アプリケーションの実行が開始される最初のファイル。
// index.html の <div id="root"></div> に React アプリをマウント（描画）する。
// Vite はこのファイルを起点に、全ての依存関係を辿ってバンドルする。
// ============================================================

// --------------------------------------------------
// React のインポート
// --------------------------------------------------

// StrictMode: 開発時に潜在的な問題を警告してくれるコンポーネント
// - 非推奨な API の使用を検知する
// - 副作用のバグを検知する（コンポーネントを2回レンダリングして検証）
// - 本番ビルドでは自動的に無効化される（パフォーマンスへの影響なし）
import { StrictMode } from "react";

// createRoot: React 19 のルート API
// React 18 から導入された新しい方法で、アプリのレンダリングを開始する
import { createRoot } from "react-dom/client";

// --------------------------------------------------
// CSS のインポート
// --------------------------------------------------
// グローバルな CSS ファイルをインポートする
// Vite では import するだけで自動的に <style> タグとして適用される
import "./index.css";

// ルートコンポーネント（App）をインポートする
import App from "./App";

// --------------------------------------------------
// React アプリのマウント（描画開始）
// --------------------------------------------------

// document.getElementById("root")! の解説:
// - document.getElementById("root") で HTML 内の <div id="root"> を取得する
// - 末尾の ! は TypeScript の「非 null アサーション演算子」
//   → "この値は null/undefined ではない" と TypeScript に伝える
//   → index.html に id="root" の要素が必ず存在することがわかっているため安全

// createRoot でルートを作成し、render で React コンポーネントを描画する
createRoot(document.getElementById("root")!).render(
  // StrictMode で囲むことで、開発中の警告を有効にする
  <StrictMode>
    {/* App コンポーネントがアプリ全体のルート */}
    <App />
  </StrictMode>
);
