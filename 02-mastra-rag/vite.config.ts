import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'

// --------------------------------------------------
// 【プロキシとは？】
// 開発時、フロントエンド (port 5173) とバックエンド (port 3001) は
// 別ポートで動作する。/api へのリクエストをバックエンドに転送する設定
// --------------------------------------------------
export default defineConfig({
  plugins: [react()],
  server: {
    proxy: {
      '/api': {
        target: 'http://localhost:3001',
        changeOrigin: true,
      },
    },
  },
})
