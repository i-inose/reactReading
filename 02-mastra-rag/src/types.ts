// --------------------------------------------------
// 【型定義とは？】
// データの形（プロパティ名と型）を事前に定義すること。
// 型を定義しておくと、間違ったプロパティ名や型のミスを
// コンパイル時に検出できる。
// --------------------------------------------------

// チャットメッセージの型
export interface ChatMessage {
  // メッセージの役割: ユーザーか AI アシスタントか
  role: "user" | "assistant";
  // メッセージ本文
  content: string;
  // AI の回答に関連するソース（引用元チャンク）
  sources?: Source[];
}

// ベクトル検索のソース（引用元）の型
export interface Source {
  // チャンクのテキスト内容
  text: string;
  // 類似度スコア（0〜1、高いほど関連性が高い）
  score: number;
}

// アップロード済みドキュメントの型
export interface Document {
  // ドキュメントの一意な ID (UUID)
  id: string;
  // ドキュメントのタイトル
  title: string;
  // 分割されたチャンク数
  chunkCount: number;
  // アップロード日時 (ISO 8601 形式)
  createdAt: string;
}

// --------------------------------------------------
// SSE（Server-Sent Events）で受信するデータの型
// type で種類を判別する Discriminated Union パターン
// --------------------------------------------------
export type SSEData =
  | { type: "text"; content: string }
  | { type: "done" }
  | { type: "error"; content: string };
