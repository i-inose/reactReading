import { Agent } from "@mastra/core/agent";
import { vectorQueryTool } from "../tools/vector-query.js";

// --------------------------------------------------
// 【Agent とは？】
// LLM（大規模言語モデル）にツールを持たせた自律的な実行単位。
// ユーザーの質問を受け取ると、必要に応じてツールを呼び出し、
// その結果をもとに回答を生成する。
// --------------------------------------------------

// --------------------------------------------------
// システムプロンプト: エージェントの振る舞いを指示する文章
// RAG では「検索結果に基づいて回答する」ことを明示するのが重要
// --------------------------------------------------
const RAG_INSTRUCTIONS = `あなたはドキュメント Q&A アシスタントです。
ユーザーの質問に対して、ベクトル検索ツールを使って関連するドキュメントを検索し、
その内容に基づいて正確に回答してください。

ルール:
- 必ずベクトル検索ツールを使って関連情報を探してください
- 検索結果に基づいて回答し、情報がない場合は正直に「該当する情報が見つかりませんでした」と伝えてください
- 回答は日本語で行ってください
- 簡潔かつ分かりやすく回答してください`;

// --------------------------------------------------
// RAG エージェントの定義
// - model: LLM として Anthropic Claude を使用
// - tools: ベクトル検索ツールを装備
// - maxSteps は generate/stream 時に指定する（ツール呼び出し回数の上限）
// --------------------------------------------------
export const ragAgent = new Agent({
  name: "RAG Agent",
  model: "anthropic/claude-sonnet-4-20250514",
  instructions: RAG_INSTRUCTIONS,
  tools: { vectorQueryTool },
});
