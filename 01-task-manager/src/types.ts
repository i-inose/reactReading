// ============================================================
// types.ts ― アプリ全体で共有する型定義
// React + TypeScript では、データの「形」を型で定義し、
// コンポーネント間で安全にデータを受け渡す
// ============================================================

// --------------------------------------------------
// タスク1件のデータ型
// API のレスポンスやコンポーネントの Props で使い回す
// --------------------------------------------------
export interface Task {
  id: number;           // タスクの一意ID
  title: string;        // タスクのタイトル
  done: boolean;        // 完了状態
  priority: Priority;   // 優先度
  createdAt: string;    // 作成日時（ISO文字列）
}

// --------------------------------------------------
// 優先度のリテラル型
// フォームの選択肢や表示ラベルで使う
// --------------------------------------------------
export type Priority = "low" | "medium" | "high";

// --------------------------------------------------
// タスク新規作成時の入力型（id と createdAt はサーバーが自動生成）
// Omit<Task, "id" | "createdAt"> と同じ意味
// --------------------------------------------------
export interface CreateTaskInput {
  title: string;
  priority: Priority;
}

// --------------------------------------------------
// タスクのフィルター条件
// "all" は全件表示、それ以外は完了/未完了で絞り込む
// --------------------------------------------------
export type FilterType = "all" | "active" | "completed";

// --------------------------------------------------
// テーマ設定（ダークモード対応）
// Context で全コンポーネントに配信する
// --------------------------------------------------
export type ThemeMode = "light" | "dark";

// --------------------------------------------------
// API レスポンスの共通型（ジェネリクス）
// 成功・エラーの両方を型安全に扱う
// --------------------------------------------------
export interface ApiResponse<T> {
  data: T;
  message: string;
}
