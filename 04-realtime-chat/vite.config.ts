// ============================================================
// vite.config.ts ― Vite の設定ファイル
//
// 【このファイルで学べること】
// - Vite の開発サーバー設定
// - プロキシ設定（フロントエンド → バックエンドの通信を中継）
// - WebSocket プロキシの設定方法
