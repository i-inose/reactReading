import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";

// --------------------------------------------------
// Vite 設定のエクスポート
// defineConfig() でエディタの補完を有効にする
// --------------------------------------------------
export default defineConfig({
  plugins: [react()],

  // --------------------------------------------------
  // 開発サーバーの設定
  //
  // 【プロキシとは？】
  // フロントエンド（localhost:5173）からバックエンド（localhost:8000）への
  // リクエストを中継する仕組み。CORS 問題を回避できる。
  // /ws で始まるリクエストを FastAPI サーバーに転送する。
  // --------------------------------------------------
  server: {
    proxy: {
      // WebSocket 接続のプロキシ設定
      // ws: true → WebSocket プロトコル（ws://）を有効にする
      "/ws": {
        target: "http://localhost:8000",
        ws: true,
      },
    },
  },
});
